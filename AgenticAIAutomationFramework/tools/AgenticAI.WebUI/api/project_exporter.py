# Bundles AI-generated Playwright scripts into a ready-to-run npm project (.zip):
# package.json, playwright.config.ts, one spec file per script, and a README.

import io
import re
import zipfile

PACKAGE_JSON = """{
  "name": "ai-generated-tests",
  "version": "1.0.0",
  "private": true,
  "scripts": {
    "test": "playwright test",
    "test:headed": "playwright test --headed",
    "report": "playwright show-report"
  },
  "devDependencies": {
    "@playwright/test": "^1.48.0"
  }
}
"""

PLAYWRIGHT_CONFIG = """import {{ defineConfig }} from '@playwright/test';

export default defineConfig({{
  testDir: './tests',
  fullyParallel: true,
  reporter: 'html',
  use: {{
    baseURL: '{base_url}',
    trace: 'on-first-retry',
    screenshot: 'only-on-failure',
  }},
}});
"""

README = """# AI-Generated Playwright Tests

Generated by the AgenticAI Web UI's AI Test Generator against:
{base_url}

## Run

```bash
npm install
npx playwright install
npm test
```

View the HTML report after a run:

```bash
npm run report
```

## Files

- `tests/` - one spec file per generated test case
- `playwright.config.ts` - base URL and reporter configuration
"""


def _slugify(name: str) -> str:
    slug = re.sub(r'[^a-zA-Z0-9]+', '-', name or 'test').strip('-').lower()
    return slug or 'test'


def build_playwright_project_zip(scripts: list, base_url: str = '') -> bytes:
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, 'w', zipfile.ZIP_DEFLATED) as zf:
        zf.writestr('package.json', PACKAGE_JSON)
        zf.writestr('playwright.config.ts', PLAYWRIGHT_CONFIG.format(base_url=base_url or 'http://localhost'))
        zf.writestr('README.md', README.format(base_url=base_url or '(not specified)'))

        used_names = set()
        for script in scripts:
            slug = _slugify(script.get('id') or script.get('name') or 'test')
            filename = slug
            counter = 2
            while filename in used_names:
                filename = f"{slug}-{counter}"
                counter += 1
            used_names.add(filename)

            body = script.get('script', '')
            content = "import { test, expect } from '@playwright/test';\n\n" + body + "\n"
            zf.writestr(f"tests/{filename}.spec.ts", content)

    return buffer.getvalue()
